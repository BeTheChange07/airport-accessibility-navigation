import os, dotenv

#Database connection parameters
DB_HOST = None
DB_PORT = None
DB_NAME = None
DB_USER = None
DB_PASS = None

#Database table names
INFRASTRUCTURE_TABLE_NAME = None
NAVMESH_NODE_TABLE_NAME = None
NAVMESH_EDGE_TABLE_NAME = None
AMENITY_TABLE_NAME = None
AMENITY_UNIT_TABLE_NAME = None

#Session management parameters
SESSION_TIMEOUT = None
SESSION_CLEANUP_INTERVAL = None
SESSION_ID_FIELD_NAME = None

def load():
    dotenv.load_dotenv()
    
    global DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASS
    DB_HOST = os.getenv("DB_HOST")
    DB_PORT = os.getenv("DB_PORT")
    DB_NAME = os.getenv("DB_NAME")
    DB_USER = os.getenv("DB_USER")
    DB_PASS = os.getenv("DB_PASSWORD")
    
    global INFRASTRUCTURE_TABLE_NAME, NAVMESH_NODE_TABLE_NAME, NAVMESH_EDGE_TABLE_NAME, AMENITY_TABLE_NAME, AMENITY_UNIT_TABLE_NAME
    INFRASTRUCTURE_TABLE_NAME = os.getenv("INFRASTRUCTURE_TABLE_NAME")
    NAVMESH_NODE_TABLE_NAME = os.getenv("NAVMESH_NODE_TABLE_NAME")
    NAVMESH_EDGE_TABLE_NAME = os.getenv("NAVMESH_EDGE_TABLE_NAME")
    AMENITY_TABLE_NAME = os.getenv("AMENITY_TABLE_NAME")
    AMENITY_UNIT_TABLE_NAME = os.getenv("AMENITY_UNIT_TABLE_NAME")
    
    global SESSION_TIMEOUT, SESSION_CLEANUP_INTERVAL, SESSION_ID_FIELD_NAME
    SESSION_TIMEOUT = int(os.getenv("SESSION_TIMEOUT"))
    SESSION_CLEANUP_INTERVAL = int(os.getenv("SESSION_CLEANUP_INTERVAL"))
    SESSION_ID_FIELD_NAME = os.getenv("SESSION_ID_FIELD_NAME")